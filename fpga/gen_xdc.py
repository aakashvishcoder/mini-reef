#!/usr/bin/env python3
"""Generate fpga/mini-reef.xdc from the KiCad netlist.

  kicad-cli sch export netlist -o /tmp/mini-reef.net mini-reef.kicad_sch
  python3 fpga/gen_xdc.py /tmp/mini-reef.net > fpga/mini-reef.xdc
"""
import re, sys

t = open(sys.argv[1]).read()
RAILS = ('GND', '+3V3', '+1V8', '+1V0')
d = {}
for m in re.finditer(r'\(net\s*\(code "\d+"\)\s*\(name "([^"]+)"\)(.*?)(?=\n\t\t\(net\b|\Z)', t, re.S):
    name = m.group(1).lstrip('/')
    if name.startswith('unconnected') or name in RAILS:
        continue
    for n in re.finditer(r'\(node\s*\(ref "U4"\)\s*\(pin "([^"]+)"\)\s*\(pinfunction "([^"]+)"\)', m.group(2)):
        ball, fn = n.groups()
        fn = re.sub(rf'_{ball}$', '', fn)          # KiCad appends the ball to some names
        if fn.startswith('IO_'):
            d[name] = (ball, fn, int(fn.rsplit('_', 1)[1]))

STD = {14: 'LVCMOS33', 15: 'LVCMOS33', 34: 'LVCMOS33', 35: 'LVCMOS18'}

def port(n):
    n = n.lower()
    m = re.match(r'(hr_dq|dbg|led|flash_dq)(\d)$', n)
    return f'{m.group(1)}[{m.group(2)}]' if m else n

GROUPS = [
    ('50 MHz clock (bank 14, MRCC)', ['CLK50']),
    ('HyperRAM, HyperBus (bank 35, byte group T1, 1.8 V)',
     ['HR_CK', 'HR_CK_N', 'HR_CS_N', 'HR_RWDS', 'HR_RST_N'] + [f'HR_DQ{i}' for i in range(8)]),
    ('Console UART to CH347T (bank 14). Named from the FPGA side.', ['UART_TX', 'UART_RX']),
    ('Test host link to the CH32V307 board, J3 (bank 15)',
     ['HOST_SCK', 'HOST_MOSI', 'HOST_MISO', 'HOST_CS_N', 'HOST_RST_N', 'HOST_START', 'HOST_DONE', 'HOST_PASS']),
    ('Debug header J4 (bank 34)', [f'DBG{i}' for i in range(8)]),
    ('User LEDs (active high) and button (active low, external 4.7k pull-up), bank 15', ['LED0', 'LED1', 'BTN_N']),
    ('Config flash data pins (bank 14). Only needed if your design reads the flash after\n'
     '# configuration. FLASH_CLK is CCLK: reach it through the STARTUPE2 primitive, not a port.',
     ['FLASH_CS_N', 'FLASH_DQ0', 'FLASH_DQ1', 'FLASH_DQ2', 'FLASH_DQ3']),
]

out = ['# Mini-Reef pin constraints for XC7A15T-1FTG256C (XC7A35T is pin-compatible).',
       '# Generated by fpga/gen_xdc.py from the KiCad netlist. Regenerate if the schematic changes.', '',
       '# Configuration: bank 0 and bank 14 are 3.3 V, boot is Master SPI x4 from the W25Q32.',
       'set_property CFGBVS VCCO [current_design]', 'set_property CONFIG_VOLTAGE 3.3 [current_design]',
       'set_property BITSTREAM.CONFIG.SPI_BUSWIDTH 4 [current_design]',
       'set_property CONFIG_MODE SPIx4 [current_design]', '']
seen = set()
for title, names in GROUPS:
    flash = names[0] == 'FLASH_CS_N'
    out.append('# ' + title)
    for n in names:
        ball, fn, bank = d[n]
        seen.add(n)
        out.append(f"{'# ' if flash else ''}set_property -dict {{PACKAGE_PIN {ball:<3} IOSTANDARD {STD[bank]}}} "
                   f"[get_ports {{{port(n)}}}]  ;# {fn}")
    if names == ['CLK50']:
        out.append('create_clock -name clk50 -period 20.000 [get_ports {clk50}]')
    out.append('')
# the one runnable check: every FPGA signal in the schematic must be covered
assert set(d) == seen, f'signals not in GROUPS: {sorted(set(d) - seen)}'
print('\n'.join(out))
